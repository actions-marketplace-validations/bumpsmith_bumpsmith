import type { JobRecord } from "../../pipeline.ts";

/**
 * Pull-request title and body (PR-1, PRD appendix A). Text that came from upstream
 * changelogs or from a model is quoted, length-capped and has @mentions neutralised, so it
 * cannot ping people or teams. Every PR states it was produced by an AI agent and names
 * the model (PRD §14 transparency; EU AI Act Art. 50).
 */

export const MAX_BODY = 60_000; // GitHub's limit is 65,536 characters

/** Break @mentions and #references so quoted text cannot notify anyone or link issues. */
export function neutralise(text: string, max = 2000): string {
  const t = text.length > max ? `${text.slice(0, max)}…` : text;
  return t
    .replace(/@(?=[A-Za-z0-9-])/g, "@​")
    .replace(/\r/g, "")
    .replace(/<!--/g, "&lt;!--");
}

const mark = (v: boolean | null | undefined) =>
  v === true ? "pass" : v === false ? "**fail**" : "–";

export function prTitle(job: JobRecord): string {
  const n = job.edits?.length ?? 0;
  const base = `Upgrade ${job.input.packageName} ${job.from ?? ""} → ${job.input.to}`.replace(
    /\s+/g,
    " ",
  );
  return n ? `${base} and adapt ${n} file${n === 1 ? "" : "s"}` : base;
}

export function prBody(opts: {
  job: JobRecord;
  appSlug: string;
  rescueOf?: number | null;
  draftReason?: string | null;
}): string {
  const { job } = opts;
  const L: string[] = [];
  const rec = job.change_record;
  if (opts.rescueOf)
    L.push(
      `Companion to #${opts.rescueOf}: the same version bump, plus the code changes it needs.`,
      "",
    );
  if (opts.draftReason) L.push(`> **Draft:** ${neutralise(opts.draftReason, 300)}`, "");

  L.push("### Summary", "", neutralise(job.impact?.reason ?? "Version bump.", 1500), "");

  if (rec?.changes.length) {
    L.push("### What changed upstream", "");
    for (const c of rec.changes.slice(0, 30)) {
      const src = c.evidence[0]?.url;
      L.push(
        `${c.id}. **${c.kind.toUpperCase()}** \`${neutralise(c.symbols.join("`, `"), 200)}\` — ${neutralise(c.instruction, 300)}${src ? ` ([source](${src}))` : ""}`,
      );
    }
    if (rec.changes.length > 30)
      L.push(`… and ${rec.changes.length - 30} more (see the job record).`);
    L.push("");
  }

  if (job.edits?.length) {
    L.push("### What changed in this repository", "");
    const byFile = new Map<string, string[]>();
    for (const it of job.impact?.items ?? []) {
      const lines = byFile.get(it.file) ?? [];
      lines.push(String(it.line));
      byFile.set(it.file, lines);
    }
    for (const e of job.edits.slice(0, 40)) {
      const lines = byFile.get(e.path);
      L.push(
        `- \`${e.path}\`${lines ? `:${lines.slice(0, 6).join(",")}` : ""}${e.allowlisted ? "" : ` — outside the impact map: ${neutralise(e.reason ?? "", 200)}`}`,
      );
    }
    L.push("");
  }

  if (job.verdict) {
    L.push("### Verification", "", "| Check | Before | After |", "|---|---|---|");
    for (const c of job.verdict.comparisons)
      L.push(`| ${c.name} | ${mark(c.baseline)} | ${mark(c.after)}${c.flaky ? " (flaky)" : ""} |`);
    if (job.verdict.preexistingFailures.length)
      L.push(
        "",
        `Already failing before the upgrade: ${job.verdict.preexistingFailures.join(", ")}.`,
      );
    L.push("");
  }

  L.push(`**Confidence: ${(job.confidence ?? "low").toUpperCase()}**`, "");
  const unverified = job.review?.unverified ?? [];
  if (unverified.length) {
    L.push("### Not verified", "");
    for (const u of unverified.slice(0, 10)) L.push(`- ${neutralise(u, 400)}`);
    L.push("");
  }
  const warns = (job.rules ?? []).filter((r) => r.severity === "warn");
  if (warns.length) {
    L.push("### Flagged for review", "");
    for (const w of warns.slice(0, 10)) L.push(`- ${w.rule}${w.file ? ` in \`${w.file}\`` : ""}`);
    L.push("");
  }
  const testsChanged = (job.rules ?? []).some(
    (r) => r.rule === "tests_changed" || r.rule === "tests_weakened",
  );
  L.push(
    `Tests changed: ${testsChanged ? "**yes — please review**" : "none"}  ·  Roll back: revert this pull request; Bumpsmith makes no data or schema changes.`,
    "",
  );
  L.push("---");
  L.push(
    `<sub>🤖 Generated by an AI agent (Bumpsmith, model \`${job.model}\`) and verified in an isolated sandbox. A human must review and merge. Job \`${job.id}\`. Commands: \`@${opts.appSlug} explain\`, \`retry\`, \`rebase\`, \`ignore this version\`, \`ignore this major\`, \`pause\`.</sub>`,
  );
  const body = L.join("\n");
  return body.length > MAX_BODY
    ? `${body.slice(0, MAX_BODY - 200)}\n\n… (truncated; full evidence is in the job record)`
    : body;
}

export function branchName(ecosystem: string, pkg: string, version: string): string {
  const safe = (s: string) =>
    s
      .replace(/^@/, "")
      .replace(/[^A-Za-z0-9._-]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 80);
  return `bumpsmith/${safe(ecosystem)}/${safe(pkg)}-${safe(version)}`;
}
